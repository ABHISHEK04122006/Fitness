    val ALL_EXERCISES: List<Exercise> by lazy {
        ALL_ENTRIES.map { toExercise(it) }
    }

    private fun normalizeBodyPart(bp: String): String {
        val s = bp.trim().lowercase()
        return when (s) {
            "abs", "core" -> "abs"
            "biceps", "triceps", "arms" -> s
            else -> s
        }
    }

    fun getExercises(bodyPart: String, level: ExperienceLevel): List<LibraryExerciseEntry> {
        val bpNorm = normalizeBodyPart(bodyPart)
        return ALL_ENTRIES.filter { entry ->
            val entryBpNorm = normalizeBodyPart(entry.bodyPart)
            val matchesBp = when (bpNorm) {
                "all" -> true
                "abs" -> entryBpNorm == "abs"
                "arms" -> entryBpNorm == "biceps" || entryBpNorm == "triceps"
                else -> entryBpNorm == bpNorm
            }
            matchesBp && entry.level == level
        }
    }

    fun getExerciseItems(bodyPart: String, level: ExperienceLevel, fallbackImage: DrawableResource? = null): List<ExerciseItem> {
        return getExercises(bodyPart, level).map { toExerciseItem(it, fallbackImage) }
    }

    fun getExercisesForLevel(level: ExperienceLevel): List<LibraryExerciseEntry> {
        return ALL_ENTRIES.filter { it.level == level }
    }

    private val entriesById: Map<String, LibraryExerciseEntry> by lazy {
        val map = HashMap<String, LibraryExerciseEntry>(ALL_ENTRIES.size * 2)
        for (entry in ALL_ENTRIES) {
            map[entry.id.trim().lowercase()] = entry
            val canon = entry.canonicalId.trim().lowercase()
            if (canon.isNotEmpty()) {
                map.putIfAbsent(canon, entry)
            }
        }
        map
    }

    private val entriesByNameNormalized: Map<String, LibraryExerciseEntry> by lazy {
        val map = HashMap<String, LibraryExerciseEntry>(ALL_ENTRIES.size * 2)
        val regex = Regex("[^a-z0-9]")
        for (entry in ALL_ENTRIES) {
            val cleanName = entry.name.trim().lowercase().replace(regex, "")
            map.putIfAbsent(cleanName, entry)
        }
        map
    }

    fun findByName(name: String): LibraryExerciseEntry? {
        val clean = name.trim().lowercase().replace(Regex("[^a-z0-9]"), "")
        return entriesByNameNormalized[clean] ?: ALL_ENTRIES.firstOrNull { it.name.trim().lowercase().replace(Regex("[^a-z0-9]"), "") == clean }
    }

    fun findById(id: String): LibraryExerciseEntry? {
        val clean = id.trim().lowercase()
        return entriesById[clean] ?: ALL_ENTRIES.firstOrNull { 
            it.id.trim().lowercase() == clean || it.canonicalId.trim().lowercase() == clean
        }
    }
