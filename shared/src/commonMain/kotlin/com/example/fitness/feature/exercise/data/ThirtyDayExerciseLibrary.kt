        val level: ExperienceLevel
    )

    fun toExercise(entry: LibraryExerciseEntry): Exercise {
        val diffEnumName = when (entry.level) {
            ExperienceLevel.NO_EXPERIENCE -> ExerciseDifficulty.NO_EXPERIENCE.name
            ExperienceLevel.BEGINNER -> ExerciseDifficulty.BEGINNER.name
            ExperienceLevel.ADVANCED -> ExerciseDifficulty.ADVANCED.name
            ExperienceLevel.EXPERT -> ExerciseDifficulty.EXPERT.name
        }
        val restSec = com.example.fitness.feature.workout.model.CustomExerciseConfig.parseDefaultRest(entry.restString)
        return Exercise(
                id = entry.id,
                name = entry.name,
                slug = entry.id.replace('_', '-'),
                description = "AthGym authoritative 30-day exercise targeting ${entry.targetMuscle} with ${entry.equipment.joinToString(", ")}.",
                primaryMuscle = entry.bodyPart,
                secondaryMuscles = if (entry.targetMuscle.equals(entry.bodyPart, ignoreCase = true)) emptyList() else listOf(entry.targetMuscle),
                muscleGroups = listOf(entry.bodyPart, entry.targetMuscle).distinct(),
                equipment = entry.equipment,
                category = ExerciseCategory.STRENGTH.name,
                difficulty = diffEnumName,
                instructions = listOf(
                    "Position yourself correctly using ${entry.equipment.joinToString(", ")}.",
                    "Initiate movement with deliberate control targeting ${entry.targetMuscle}.",
                    "Complete full range of motion with strict tempo and peak contraction."
                ),
                setupSteps = listOf("Set up with ${entry.equipment.joinToString(", ")}", "Establish solid base and brace core"),
                executionSteps = listOf("Perform ${entry.defaultSets} sets of ${entry.defaultReps}", "Rest for ${restSec}s between sets"),
                formTips = listOf("Control the eccentric negative phase", "Maintain tension on ${entry.targetMuscle}"),
                defaultSets = entry.defaultSets,
                defaultReps = entry.defaultReps,
                defaultRestSeconds = restSec,
                media = ExerciseMedia(mediaType = "IMAGE"),
                isActive = true,
                version = 1
            )
        }

    fun toExerciseItem(entry: LibraryExerciseEntry, fallbackImage: DrawableResource? = null): ExerciseItem {
        val resolvedImage = fallbackImage ?: FullBodyExerciseLibrary.resolveExerciseImage(entry.name, entry.id)
        val repsStr = entry.defaultReps.ifBlank { "10-12" }
        val setsDisplay = "${entry.defaultSets} sets × $repsStr"
        val durationDisplay = "${(entry.defaultSets * 2).coerceAtLeast(5)} min"
        val restSec = com.example.fitness.feature.workout.model.CustomExerciseConfig.parseDefaultRest(entry.restString)
        return ExerciseItem(
            id = entry.id,
            name = entry.name,
            sets = setsDisplay,
            duration = durationDisplay,
            description = "Prescribed movement targeting ${entry.targetMuscle} with ${entry.equipment.joinToString(", ")}.",
            imageRes = resolvedImage,
            videoDemoUrl = "",
            tips = listOf("Control tempo throughout repetitions", "Rest ${restSec}s between sets"),
            restTime = "${restSec}s"
        )
    }

